"""Write design/sample-data.js from data/processed/ so the static mockups use real numbers.

Run from the repo root: scraper/.venv/Scripts/python design/make_sample_data.py
"""

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PROCESSED = ROOT / "data" / "processed"

CATEGORIES = [
    {"id": "beras", "name": "Beras & biji-bijian"},
    {"id": "bumbu", "name": "Bumbu"},
    {"id": "daging-telur", "name": "Daging & telur"},
    {"id": "ikan", "name": "Ikan"},
    {"id": "minyak-gula-tepung", "name": "Minyak, gula & tepung"},
]

commodities = yaml.safe_load((ROOT / "scraper/config/commodities.yaml").read_text(encoding="utf-8"))
regions = yaml.safe_load((ROOT / "scraper/config/regions.yaml").read_text(encoding="utf-8"))
latest = json.loads((PROCESSED / "latest.json").read_text(encoding="utf-8"))

history = {}
for c in commodities:
    h = json.loads((PROCESSED / "history" / f"{c['id']}.json").read_text(encoding="utf-8"))
    history[c["id"]] = [[p["date"], p["price"]] for p in h["series"]["diy"]]

data = {
    "updatedAt": latest["updated_at"],
    "source": latest["source"],
    "categories": CATEGORIES,
    "regions": [{"id": r["id"], "name": r["name"]} for r in regions],
    "commodities": [
        {"id": c["id"], "name": c["name"], "category": c["category"], "unit": c["unit"]}
        for c in commodities
    ],
    "latest": {
        region: {
            cid: {k: v[k] for k in ("date", "price", "change_7d_pct", "spike")}
            for cid, v in items.items()
        }
        for region, items in latest["regions"].items()
    },
    "historyDiy": history,
}

out = Path(__file__).resolve().parent / "sample-data.js"
out.write_text(
    "// Generated by design/make_sample_data.py from data/processed/. Do not edit by hand.\n"
    f"window.REGO_DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n",
    encoding="utf-8",
)
print(f"wrote {out} ({out.stat().st_size} bytes)")
